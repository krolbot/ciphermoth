#!/bin/sh
# CipherMoth installer: pulls the signed images and starts your vault (one
# SQLite file in a Docker volume). Safe to read before you run it.
#
#   curl -fsSL https://raw.githubusercontent.com/mr-grj/ciphermoth/master/install.sh | sh
#
# Overridable with env vars: CIPHERMOTH_REPO, CIPHERMOTH_REF, CIPHERMOTH_DIR.
set -eu

REPO="${CIPHERMOTH_REPO:-mr-grj/ciphermoth}"
REF="${CIPHERMOTH_REF:-master}"
BASE="https://raw.githubusercontent.com/${REPO}/${REF}"
DIR="${CIPHERMOTH_DIR:-ciphermoth}"

GLOW='\033[38;5;79m'
BOLD='\033[1m'
RED='\033[31m'
NC='\033[0m'

say() { printf '%b\n' "${GLOW}▪${NC} $*"; }
info() { printf '%b\n' "  $*"; }
warn() { printf '%b\n' "${RED}!${NC} $*"; }
die() {
  printf '%b\n' "${RED}✗ $*${NC}" >&2
  exit 1
}

have() { command -v "$1" >/dev/null 2>&1; }

start_stack() {
  docker compose -f docker-compose.prod.yml pull &&
    docker compose -f docker-compose.prod.yml up -d --remove-orphans
}

ask_yes_no() {
  _q="$1"
  _def="$2"
  _ans=""
  if [ -r /dev/tty ]; then
    printf '%b ' "$_q"
    read -r _ans </dev/tty || _ans=""
  fi
  [ -z "$_ans" ] && _ans="$_def"
  case "$_ans" in
    y | Y | yes | YES) return 0 ;;
    *) return 1 ;;
  esac
}

ensure_docker() {
  if ! have docker; then
    if [ "$(uname -s)" = "Linux" ] && ask_yes_no \
      "Docker isn't installed. Install it now via Docker's official script? [Y/n]" "Y"; then
      curl -fsSL https://get.docker.com | sh
    else
      die "Install Docker first: https://docs.docker.com/get-docker/"
    fi
  fi
  docker compose version >/dev/null 2>&1 ||
    die "Docker Compose v2 is missing. Update Docker Desktop or install the compose plugin."
  docker info >/dev/null 2>&1 ||
    die "Docker doesn't seem to be running (or needs sudo). Start it and re-run."
}

main() {
  say "${BOLD}CipherMoth${NC} -> your secrets stay in the dark."
  ensure_docker

  if docker volume inspect ciphermoth_postgres_data >/dev/null 2>&1; then
    warn "Found a vault from an older CipherMoth that used PostgreSQL."
    warn "This release keeps the vault in SQLite and starts a fresh, empty one;"
    warn "the old database volume is left untouched (docs/UPDATING.md)."
    ask_yes_no "Replace the old containers with a fresh vault? [y/N]" \
      "${CIPHERMOTH_FRESH:-N}" || die "Stopped. Nothing was changed."
  fi

  mkdir -p "$DIR"
  cd "$DIR"
  say "Installing into $(pwd)"

  curl -fsSL "$BASE/docker-compose.prod.yml" -o docker-compose.prod.yml.new ||
    die "Could not download docker-compose.prod.yml"
  if [ -f docker-compose.prod.yml ] && ! cmp -s docker-compose.prod.yml docker-compose.prod.yml.new; then
    cp docker-compose.prod.yml docker-compose.prod.yml.previous
    info "Kept your previous compose file as docker-compose.prod.yml.previous"
  fi
  mv docker-compose.prod.yml.new docker-compose.prod.yml

  if curl -fsSL "$BASE/scripts/cip" -o cip.tmp 2>/dev/null && [ -s cip.tmp ]; then
    mv cip.tmp cip
    chmod +x cip
  else
    rm -f cip.tmp
    warn "Could not download the 'cip' CLI shortcut; the vault itself is unaffected."
  fi

  if [ -f .env ]; then
    info ".env already exists -> keeping your existing settings."
    if grep -Eq '^CIPHERMOTH_VERSION=v?1\.' .env; then
      cp .env .env.previous
      sed 's/^CIPHERMOTH_VERSION=.*/CIPHERMOTH_VERSION=latest/' .env.previous >.env
      warn "Your .env pinned a 1.x release, which needs PostgreSQL; it now says"
      warn "CIPHERMOTH_VERSION=latest (the old file is .env.previous)."
    fi
  else
    cat >.env <<EOF
# CipherMoth configuration. Generated by install.sh.
# Full reference: https://github.com/${REPO}/blob/master/.env.prod.example

# Image version: "latest", or pin to a release like 2.0.0 (no leading "v").
CIPHERMOTH_VERSION=latest

# On a server (not localhost), point these at your host or domain:
# CIPHERMOTH_API_URL=http://your-host:8000/api
# CIPHERMOTH_FRONTEND_ORIGIN=http://your-host:3000

# The UI and API listen on 127.0.0.1 only. To reach them from other machines
# directly (not through a reverse proxy on this host), uncomment:
# CIPHERMOTH_BIND_ADDRESS=0.0.0.0
EOF
  fi

  say "Pulling signed images and starting CipherMoth…"
  start_stack || die "Failed to start CipherMoth. Check the output above."

  printf '\n'
  say "${BOLD}CipherMoth is up.${NC}"
  info "Open ${BOLD}http://localhost:3000${NC} and create your master password."
  info "Folder: $(pwd)"
  info "Stop:   docker compose -f docker-compose.prod.yml down"
  if [ -x ./cip ]; then
    printf '\n'
    info "Prefer the terminal? ${BOLD}./cip password list${NC} (try ${BOLD}./cip --help${NC})"
    info "Use it from anywhere: ${BOLD}sudo ln -s $(pwd)/cip /usr/local/bin/cip${NC}"
  fi
  printf '\n'
  warn "There is no password recovery. Write your master password down somewhere safe,"
  warn "and take a backup once you've added a few entries."
  info "Before every update: ${BOLD}docker compose -f docker-compose.prod.yml exec backend ciphermoth-admin snapshot${NC}"
}

main
